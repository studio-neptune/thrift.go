// legySbox is the 256-byte lookup table extracted verbatim from
// LINE APK v12.21.1 lib/arm64-v8a/liblegy.so at vaddr 0xf173 (file offset
// 0xf173 in .rodata; referenced by lec_get_serialno @0x182c8 via
// `adrp x9, 0xf000; add x9, x9, #0x173`).
//
// NOTE: despite the historical "S-box" name, the table is NOT a
// permutation of 0..255; it is the standard base64 *decode* table:
// legySbox[c] is the 6-bit value of base64 alphabet char c, and 0x40
// for any non-alphabet byte. lec_get_serialno therefore base64-decodes
// the first 3 frame bytes into a 16-bit serial (the low 2 bits of the
// third char are discarded by the native packing).
