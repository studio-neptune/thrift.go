// legySboxInv maps a 6-bit value back to its base64 alphabet byte,
// built from legySbox so EncodeSerial is an exact inverse of DecodeSerial.
var legySboxInv = func() [64]byte {
	var inv [64]byte
	for c := 0; c < 256; c++ {
		if v := legySbox[c]; v < 64 {
			inv[v] = byte(c)
		}
	}
	return inv
}()

// DecodeSerial reproduces lec_get_serialno @0x182c8 bit-for-bit:
//
//	t0, t1, t2 := legySbox[b0], legySbox[b1], legySbox[b2]
//	lo     = ((t0 & 0x3f) << 2) | (t1 >> 4)
//	hi     = ((t1 & 0x0f) << 4) | (t2 >> 2)
//	serial = (hi << 8) | lo
func DecodeSerial(b0, b1, b2 byte) uint16 {
	t0, t1, t2 := legySbox[b0], legySbox[b1], legySbox[b2]
	lo := uint16(((t0&0x3f)<<2)|(t1>>4)) & 0xff
	hi := uint16(((t1&0x0f)<<4)|(t2>>2)) & 0xff
	return hi<<8 | lo
}

// EncodeSerial is the inverse of DecodeSerial: it packs a 16-bit serial
// into 3 wire chars (low byte first, then high byte, 6 bits per char
// through the base64 alphabet), matching the native decode packing.
func EncodeSerial(serial uint16) [3]byte {
	lo := serial & 0xff
	hi := serial >> 8
	v0 := lo >> 2
	v1 := ((lo & 0x03) << 4) | (hi >> 4)
	v2 := (hi & 0x0f) << 2
	return [3]byte{legySboxInv[v0], legySboxInv[v1], legySboxInv[v2]}
}

// DecodeSerialBytes decodes the serial from the first 3 chars of a base64
// wire frame — the exact native bit packing of lec_get_serialno @0x182c8
// (6 bits per char; the low 2 bits of the third char belong to the next
// decoded byte and are discarded). The result equals the 16-bit LE value
// of the first two decoded bytes.
func DecodeSerialBytes(frameWire [3]byte) uint16 {
	return DecodeSerial(frameWire[0], frameWire[1], frameWire[2])
}

// EncodeSerialBytes packs a 16-bit serial into the first 3 base64 chars of a
// wire frame — the inverse of DecodeSerialBytes. For a frame
// base64(serial_LE16 || body), these are exactly the frame's first 3 chars
// (the low 2 bits of the third char are the first 2 bits of body[0], zero
// when encoding the serial alone).
func EncodeSerialBytes(serial uint16) [3]byte {
	return EncodeSerial(serial)
}
